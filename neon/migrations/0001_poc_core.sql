CREATE SCHEMA IF NOT EXISTS chess_simul;

REVOKE ALL ON SCHEMA chess_simul FROM PUBLIC;

CREATE TABLE IF NOT EXISTS chess_simul.profiles (
  id uuid PRIMARY KEY,
  username text NOT NULL UNIQUE,
  avatar_url text,
  bio text,
  elo integer NOT NULL DEFAULT 1200,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chess_simul.simuls (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  host_id uuid NOT NULL REFERENCES chess_simul.profiles(id),
  name text NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','running','closed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chess_simul.games (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  simul_id uuid REFERENCES chess_simul.simuls(id) ON DELETE SET NULL,
  white_id uuid NOT NULL REFERENCES chess_simul.profiles(id),
  black_id uuid NOT NULL REFERENCES chess_simul.profiles(id),
  status text NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting','active','checkmate','draw','resigned','aborted','white_won','black_won')),
  turn char(1) NOT NULL DEFAULT 'w' CHECK (turn IN ('w','b')),
  fen text NOT NULL DEFAULT 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1',
  move_count integer NOT NULL DEFAULT 0 CHECK (move_count >= 0),
  last_move_uci text,
  clocks jsonb,
  winner_id uuid REFERENCES chess_simul.profiles(id),
  game_mode text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (white_id <> black_id)
);

CREATE TABLE IF NOT EXISTS chess_simul.moves (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id uuid NOT NULL REFERENCES chess_simul.games(id) ON DELETE CASCADE,
  ply integer NOT NULL CHECK (ply > 0),
  uci text NOT NULL,
  san text,
  fen_after text NOT NULL,
  played_by uuid NOT NULL REFERENCES chess_simul.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (game_id, ply)
);

CREATE TABLE IF NOT EXISTS chess_simul.simul_tables (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  simul_id uuid NOT NULL REFERENCES chess_simul.simuls(id) ON DELETE CASCADE,
  seat_no integer NOT NULL CHECK (seat_no > 0),
  guest_id uuid REFERENCES chess_simul.profiles(id),
  game_id uuid REFERENCES chess_simul.games(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'free' CHECK (status IN ('free','reserved','playing','done')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(simul_id,seat_no)
);

CREATE TABLE IF NOT EXISTS chess_simul.match_queue (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE REFERENCES chess_simul.profiles(id) ON DELETE CASCADE,
  time_control text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS chess_simul.simul_round_robin_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organizer_id uuid NOT NULL REFERENCES chess_simul.profiles(id),
  invite_code text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','started','completed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  started_at timestamptz
);

CREATE TABLE IF NOT EXISTS chess_simul.simul_round_robin_participants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id uuid NOT NULL REFERENCES chess_simul.simul_round_robin_sessions(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES chess_simul.profiles(id),
  status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','left')),
  joined_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(session_id,user_id)
);

CREATE TABLE IF NOT EXISTS chess_simul.simul_round_robin_game_links (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id uuid NOT NULL REFERENCES chess_simul.simul_round_robin_sessions(id) ON DELETE CASCADE,
  game_id uuid NOT NULL REFERENCES chess_simul.games(id) ON DELETE CASCADE,
  white_id uuid NOT NULL REFERENCES chess_simul.profiles(id),
  black_id uuid NOT NULL REFERENCES chess_simul.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK(white_id <> black_id),
  UNIQUE(session_id,white_id,black_id)
);

CREATE INDEX IF NOT EXISTS neon_games_white_idx ON chess_simul.games(white_id);

CREATE INDEX IF NOT EXISTS neon_games_black_idx ON chess_simul.games(black_id);

CREATE INDEX IF NOT EXISTS neon_games_simul_idx ON chess_simul.games(simul_id);

CREATE INDEX IF NOT EXISTS neon_moves_game_ply_idx ON chess_simul.moves(game_id,ply);

CREATE INDEX IF NOT EXISTS neon_simuls_host_idx ON chess_simul.simuls(host_id);

CREATE INDEX IF NOT EXISTS neon_rr_participants_user_idx ON chess_simul.simul_round_robin_participants(user_id);

ALTER TABLE chess_simul.profiles ENABLE ROW LEVEL SECURITY;

ALTER TABLE chess_simul.simuls ENABLE ROW LEVEL SECURITY;

ALTER TABLE chess_simul.games ENABLE ROW LEVEL SECURITY;

ALTER TABLE chess_simul.moves ENABLE ROW LEVEL SECURITY;

ALTER TABLE chess_simul.simul_tables ENABLE ROW LEVEL SECURITY;

ALTER TABLE chess_simul.match_queue ENABLE ROW LEVEL SECURITY;

ALTER TABLE chess_simul.simul_round_robin_sessions ENABLE ROW LEVEL SECURITY;

ALTER TABLE chess_simul.simul_round_robin_participants ENABLE ROW LEVEL SECURITY;

ALTER TABLE chess_simul.simul_round_robin_game_links ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA chess_simul FROM PUBLIC;

REVOKE ALL ON ALL SEQUENCES IN SCHEMA chess_simul FROM PUBLIC;
